#!/usr/bin/env python3
"""Plain-English release notes from what went live (roadmap S1-5).

    python scripts/release_notes.py              # write docs/RELEASES.md
    python scripts/release_notes.py --days 14    # how far back (default 60)

Every change reaches main as one squash-merged pull request whose title is
already written for people ("help: a page for every Runner section..."),
and Railway deploys each merge. So the list of merges on main IS the list
of releases. This groups them by day (in Adelaide), newest first, with the
commit to roll back to (scripts/rollback.py) and the PR link.
"""
import argparse
import os
import re
import subprocess
from collections import OrderedDict
from datetime import datetime, timedelta, timezone

try:
    from zoneinfo import ZoneInfo
except ImportError:  # pragma: no cover
    ZoneInfo = None

REPO = "fruithappens/Coffeecue"
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(ROOT, "docs", "RELEASES.md")
TZ = "Australia/Adelaide"

# "area: what changed (#123)" -> ("area", "what changed", 123)
TITLE = re.compile(r"^(?:([a-z][\w /-]{1,30}):\s*)?(.*?)(?:\s*\(#(\d+)\))?$")


def merges(days):
    since = (datetime.now(timezone.utc) - timedelta(days=days)).strftime("%Y-%m-%d")
    out = subprocess.run(
        [
            "git",
            "log",
            "origin/main",
            "--first-parent",
            f"--since={since}",
            "--format=%H%x09%cI%x09%s",
        ],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    for line in out.splitlines():
        sha, when, subject = line.split("\t", 2)
        yield sha, datetime.fromisoformat(when), subject


def render(days):
    tz = ZoneInfo(TZ) if ZoneInfo else timezone.utc
    by_day = OrderedDict()
    for sha, when, subject in merges(days):
        m = TITLE.match(subject.strip())
        area, what, pr = (m.group(1) or ""), (m.group(2) or subject), m.group(3)
        local = when.astimezone(tz)
        by_day.setdefault(local.strftime("%A %d %B %Y"), []).append(
            (local.strftime("%H:%M"), area, what, pr, sha[:7])
        )
    lines = [
        "# What's changed in CupQ",
        "",
        "Every change that went live, newest first, in the words of the change itself.",
        "Times are Adelaide. To go back to a version, use its code with",
        "`scripts/rollback.py` (see docs/ROLLBACK.md).",
        "",
        f"_Generated by scripts/release_notes.py; last {days} days._",
        "",
    ]
    for day, items in by_day.items():
        lines += [f"## {day}", ""]
        for t, area, what, pr, sha in items:
            link = f" ([#{pr}](https://github.com/{REPO}/pull/{pr}))" if pr else ""
            tag = f"**{area}**: " if area else ""
            lines.append(f"- {t} {tag}{what[:1].upper() + what[1:]}{link} `{sha}`")
        lines.append("")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--days", type=int, default=60)
    a = ap.parse_args()
    text = render(a.days)
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {text.count(chr(10) + '- ')} changes")


if __name__ == "__main__":
    main()
